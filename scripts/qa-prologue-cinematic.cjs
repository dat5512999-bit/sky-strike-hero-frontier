'use strict';
const { chromium } = require('playwright');
const assert = require('node:assert/strict'), fs = require('node:fs');
const url = process.env.PROLOGUE_TEST_URL || 'http://127.0.0.1:4175/td.html';
(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const out = 'artifacts/qa-prologue-v0833'; fs.mkdirSync(out, { recursive: true });
  const errors = [], checks = [];
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, serviceWorkers: 'block' });
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(url); await page.waitForFunction(() => globalThis.frontierApp);
    await page.locator('[data-action="story"]').first().click();
    await page.locator('[data-action="cinematic"]').first().click();
    await page.locator('.hf-cinematic-frame').waitFor({ state: 'visible' });
    await page.locator('.hf-cinematic-image').waitFor({ state: 'visible' });
    assert.equal(await page.locator('.hf-cinematic-image').evaluate(image => image.complete && image.naturalWidth > 0), true);
    assert.match(await page.locator('.hf-cinematic-story-copy').textContent(), /人類、銀葉與暮影/);
    assert.equal(await page.locator('.hf-cinematic option:disabled').count(), 2);
    await page.getByRole('button', { name: '暫停', exact: true }).click();
    const time = await page.locator('.hf-cinematic-time').textContent();
    await page.waitForTimeout(1100); assert.equal(await page.locator('.hf-cinematic-time').textContent(), time);
    await page.getByRole('button', { name: '下一張分鏡', exact: true }).click();
    await page.locator('.hf-cinematic-story-copy').waitFor({ state: 'visible' });
    assert.match(await page.locator('.hf-cinematic-story-copy').textContent(), /第一次真正的交流/);
    await page.getByRole('button', { name: '上一張分鏡', exact: true }).click();
    await page.locator('.hf-cinematic-image').waitFor({ state: 'visible' });
    assert.match(await page.locator('.hf-cinematic-story-copy').textContent(), /曾經的世界/);
    assert.match(await page.locator('.hf-cinematic-music').textContent(), /配樂|開啟/);
    await page.screenshot({ path: out + '/key-art-desktop.png' });
    await page.getByRole('button', { name: '繼續播放', exact: true }).click();
    await page.getByRole('button', { name: '跳過，進入第一章', exact: true }).click();
    await page.locator('[data-action="chapter-battle"]').waitFor();
    let state = await page.evaluate(() => frontierApp.store.current());
    assert.deepEqual(state.completed, []); assert.ok(state.cinematics.includes('cinematic:prologue_before_shattered_peace'));
    await page.locator('[data-action="chapter-battle"]').click();
    assert.match(await page.locator('.story-card').textContent(), /邊境烽火亮起/);
    await page.locator('[data-action="story-card-next"]').click();
    assert.match(await page.locator('.story-card').textContent(), /對面也是王國士兵/);
    await page.locator('[data-action="story-card-skip"]').click();
    assert.equal(await page.evaluate(() => document.body.dataset.appPage), 'battle');
    await page.evaluate(() => frontierApp.home());
    checks.push('HTTP 404 video + shipped key art: image decode, pause, skip, atomic collection, Chapter I cards and battle');
    await page.locator('[data-action="codex"]').click();
    await page.waitForFunction(() => globalThis.HeroFrontierCodex);
    await page.locator('[data-category="chronicle"]').click();
    await page.locator('.cinematic-inbox').click();
    assert.match(await page.locator('#modal-body').textContent(), /CONFIRMED \/ STORY EXPERIENCE/);
    const before = await page.evaluate(() => HeroFrontierCodex.progression.save.profileStore.export());
    await page.getByRole('button', { name: 'Replay Cinematic · 重播影片', exact: true }).click();
    await page.locator('.hf-cinematic-frame').waitFor({ state: 'visible' });
    await page.setViewportSize({ width: 844, height: 390 });
    await page.screenshot({ path: out + '/key-art-mobile.png' });
    const bounds = await page.locator('.hf-cinematic-skip').boundingBox();
    assert.ok(bounds.x >= 0 && bounds.y >= 0 && bounds.x + bounds.width <= 844 && bounds.y + bounds.height <= 390);
    await page.keyboard.press('Escape');
    await page.locator('.hf-cinematic').waitFor({ state: 'detached' });
    assert.equal(await page.evaluate(() => HeroFrontierCodex.progression.save.profileStore.export()), before);
    checks.push('Chronicle replay, Escape, landscape controls, no story/save changes');
    await page.setViewportSize({ width: 390, height: 844 });
    await page.locator('.cinematic-inbox').click();
    await page.getByRole('button', { name: 'Replay Cinematic · 重播影片', exact: true }).click();
    await page.locator('.hf-cinematic-frame').waitFor({ state: 'visible' });
    await page.screenshot({ path: out + '/key-art-portrait.png' });
    const portrait = await page.locator('.hf-cinematic-skip').boundingBox();
    assert.ok(portrait.x + portrait.width <= 390 && portrait.y + portrait.height <= 844);
    await page.keyboard.press('Escape'); await page.locator('.hf-cinematic').waitFor({ state: 'detached' });
    await page.setViewportSize({ width: 1440, height: 900 });
    await page.locator('a[aria-label="返回遊戲"]').click(); await page.waitForFunction(() => globalThis.frontierApp);
    await page.locator('[data-action="story"]').first().click(); await page.locator('[data-action="cinematic"]').first().click();
    await page.locator('[data-action="story-card-skip"]').click();
    await page.waitForFunction(() => document.body.dataset.appPage === 'battle');
    assert.equal(await page.locator('.hf-cinematic').count(), 0);
    checks.push('persisted Continue bypasses prologue, offers story cards, and reaches existing Story mission');

    // Accelerate only the storyboard clock; no video or story content is synthesized.
    const natural = await browser.newPage({ viewport: { width: 1440, height: 900 }, serviceWorkers: 'block' });
    natural.on('pageerror', error => errors.push(error.message));
    await natural.goto(url); await natural.waitForFunction(() => globalThis.frontierApp);
    await natural.clock.install();
    await natural.locator('[data-action="story"]').first().click(); await natural.locator('[data-action="cinematic"]').first().click();
    await natural.locator('.hf-cinematic-frame').waitFor({ state: 'visible' });
    await natural.clock.fastForward(14500);
    assert.match(await natural.locator('.hf-cinematic-captions').textContent(), /我們曾相信/);
    await natural.locator('.hf-cinematic select').selectOption('off'); await natural.clock.fastForward(100);
    assert.equal(await natural.locator('.hf-cinematic-captions').textContent(), '');
    await natural.clock.fastForward(43500);
    await natural.locator('.hf-cinematic-title-card').waitFor({ state: 'visible' });
    assert.match(await natural.locator('.hf-cinematic-title-card').textContent(), /HERO FRONTIER/);
    await natural.screenshot({ path: out + '/key-art-title.png' });
    await natural.clock.fastForward(2600);
    await natural.locator('[data-action="chapter-battle"]').waitFor();
    checks.push('natural 60-second storyboard completion, timed captions and subtitles off');

    // Exercise delayed / invalid media and autoplay rejection using controlled browser fixtures.
    await natural.evaluate(async () => { frontierApp.store.newRound(); frontierApp.home(); });
    await natural.route('**/prologue_zh_tw.mp4', route => route.fulfill({ status: 200, contentType: 'video/mp4', body: 'invalid-mp4' }));
    await natural.locator('[data-action="story"]').first().click(); await natural.locator('[data-action="cinematic"]').first().click();
    await natural.locator('.hf-cinematic-frame').waitFor({ state: 'visible' });
    await natural.getByRole('button', { name: '跳過，進入第一章', exact: true }).click();
    checks.push('corrupt media falls back and can skip');
    await natural.unroute('**/prologue_zh_tw.mp4');
    await natural.evaluate(() => { frontierApp.store.newRound(); frontierApp.home(); HTMLMediaElement.prototype.play = function () { return Promise.reject(new DOMException('blocked', 'NotAllowedError')); }; });
    await natural.route('**/prologue_zh_tw.mp4', () => {});
    await natural.locator('[data-action="story"]').first().click(); await natural.locator('[data-action="cinematic"]').first().click();
    await natural.getByRole('button', { name: '點此播放', exact: true }).waitFor();
    await natural.getByRole('button', { name: '使用分鏡預覽', exact: true }).click();
    await natural.locator('.hf-cinematic-frame').waitFor({ state: 'visible' });
    await natural.getByRole('button', { name: '跳過，進入第一章', exact: true }).click();
    checks.push('autoplay rejection retains usable preview and skip controls');
    assert.deepEqual(errors, []);
    fs.writeFileSync(out + '/results.json', JSON.stringify({ errors, checks }, null, 2));
    console.log(JSON.stringify({ errors, checks }, null, 2));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
