'use strict';
// Measurement only: source PNGs are never resampled or edited.
const fs=require('node:fs'),{rgba}=require('../tests/png-pixels.cjs');
const types=['frostWolf','frostBear','frostBird','frostHunter','frostShaman','frostMammoth'];
function measure(type){
  const path=`assets/td/frostland/${type}-motion-v2.png`,{width,height,pixels}=rgba(path);
  const labels=new Int32Array(width*height),queue=new Int32Array(width*height),components=[];
  for(let start=0;start<labels.length;start++){
    if(labels[start]||pixels[start*4+3]<80)continue;
    const id=components.length+1;let size=1,index=0,left=width,top=height,right=0,bottom=0;
    queue[0]=start;labels[start]=id;
    while(index<size){
      const p=queue[index++],x=p%width,y=Math.floor(p/width);
      left=Math.min(left,x);right=Math.max(right,x);top=Math.min(top,y);bottom=Math.max(bottom,y);
      for(const n of [x?p-1:-1,x<width-1?p+1:-1,y?p-width:-1,y<height-1?p+width:-1]){
        if(n>=0&&!labels[n]&&pixels[n*4+3]>=80){labels[n]=id;queue[size++]=n;}
      }
    }
    components.push({id,size,left,top,right,bottom});
  }
  const bodies=components.filter(c=>c.size>1800);
  if(bodies.length!==16)throw Error(`${type}: expected 16 separate bodies, found ${bodies.length}`);
  const frames=Array(16);
  for(const body of bodies){
    const column=Math.min(3,Math.floor((body.left+body.right)/2/width*4));
    const row=Math.min(3,Math.floor((body.top+body.bottom)/2/height*4)),index=row*4+column;
    if(frames[index])throw Error(`${type}: two bodies assigned to frame ${index}`);
    // Include soft alpha edges beyond the solid silhouette. Keep original size.
    const left=Math.max(0,body.left-3),top=Math.max(0,body.top-3),right=Math.min(width-1,body.right+3),bottom=Math.min(height-1,body.bottom+3);
    const cuts=[];
    for(const other of bodies){
      if(other===body)continue;
      if(other.left<=right&&other.right>=left&&other.top<=bottom&&other.bottom>=top){
        // Never use a rectangular cut that could remove part of this body.
        throw Error(`${type}: overlapping frame bounds ${index}; regenerate with more spacing`);
      }
    }
    // Anchor to the feet rather than the full silhouette: an extended claw,
    // bow or wing must not push the torso sideways when its bounds widen.
    let footX=0,footCount=0;
    for(let y=Math.max(body.top,body.bottom-10);y<=body.bottom;y++)for(let x=body.left;x<=body.right;x++){
      if(labels[y*width+x]===body.id){footX+=x;footCount++;}
    }
    frames[index]={rect:[left,top,right-left+1,bottom-top+1],anchorX:footCount?Math.round(footX/footCount):(body.left+body.right)/2,foot:body.bottom+1,cuts};
  }
  return {path,width,height,columns:4,rows:4,maxHeight:Math.max(...frames.map(f=>f.rect[3])),frames};
}
if(require.main===module){
  const data=Object.fromEntries(types.map(type=>[type,measure(type)]));
  if(process.argv.includes('--write'))fs.writeFileSync('src/td/systems/FrostlandMotionAtlas.js',`// Generated by scripts/measure-frostland-motion.cjs; source pixels unchanged.\n(function(ns){ns.systems.FrostlandMotionAtlas=${JSON.stringify(data)};})(globalThis.TowerFrontier);\n`);
  console.log(Object.fromEntries(Object.entries(data).map(([key,v])=>[key,{frames:v.frames.length,size:[v.width,v.height],maxHeight:v.maxHeight}])));
}
module.exports={measure};
